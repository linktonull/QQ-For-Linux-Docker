        -e DBUS_SESSION_BUS_ADDRESS="$DBUS_SESSION_BUS_ADDRESS" \
        -e UID=$(id -u) \
        -e WAYLAND_DISPLAY=$WAYLAND_DISPLAY \
        -e XDG_SESSION_TYPE=$XDG_SESSION_TYPE \
        -e LANG=zh_CN.UTF-8 \
        -e TZ=Asia/Shanghai \
        -e XMODIFIERS \
        -e QT_IM_MODULE \
        -e GTK_IM_MODULE \
